MODULES = [
    "app", "feature/backup", "feature/connect", "feature/launcher",
    "feature/manage", "feature/modules", "feature/setup", "ui/design", "tv/curtain",
]

def main():
    written = 0
    for module in MODULES:
        source = ROOT / module / "src/main/res/values/strings.xml"
        if not source.exists():
            continue
        tree = ET.parse(source)
        original = tree.getroot()
        out = ET.Element("resources")
        for item in list(original):
            if item.tag == "string":
                key = item.attrib.get("name")
                if key in RU and item.attrib.get("translatable") != "false":
                    node = ET.SubElement(out, "string", {"name": key})
                    node.text = RU[key]
                    if item.attrib.get("formatted") == "false":
                        node.set("formatted", "false")
                    written += 1
            elif item.tag == "plurals":
                key = item.attrib.get("name")
                if key in PLURALS:
                    node = ET.SubElement(out, "plurals", {"name": key})
                    for quantity, value in PLURALS[key].items():
                        child = ET.SubElement(node, "item", {"quantity": quantity})
                        child.text = value
                    written += 1
        if len(out):
            target = source.parent.parent / "values-ru" / "strings.xml"
            target.parent.mkdir(parents=True, exist_ok=True)
            ET.indent(out, space="    ")
            target.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(out, encoding="unicode") + "\n", encoding="utf-8")
    print(f"Russian localization generated: {written} translated resource entries.")

if __name__ == "__main__":
    main()
